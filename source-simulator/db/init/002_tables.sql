CREATE TABLE IF NOT EXISTS source_incremental.customers (
    customer_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_name VARCHAR(200) NOT NULL,
    email VARCHAR(320) NOT NULL UNIQUE,
    country VARCHAR(100) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE IF NOT EXISTS source_incremental.products (
    product_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_name VARCHAR(200) NOT NULL,
    category VARCHAR(100) NOT NULL,
    unit_of_measure VARCHAR(30) NOT NULL DEFAULT 'piece',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE IF NOT EXISTS source_incremental.orders (
    order_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL REFERENCES source_incremental.customers(customer_id),
    order_date TIMESTAMPTZ NOT NULL,
    status VARCHAR(20) NOT NULL
        CHECK (status IN ('NEW', 'CONFIRMED', 'PROCESSING', 'SHIPPED', 'DELIVERED', 'CANCELLED')),
    country VARCHAR(100) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE IF NOT EXISTS source_incremental.order_items (
    order_item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES source_incremental.orders(order_id),
    product_id BIGINT NOT NULL REFERENCES source_incremental.products(product_id),
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    unit_price NUMERIC(12, 2) NOT NULL CHECK (unit_price >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE OR REPLACE FUNCTION source_incremental.set_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at = clock_timestamp();
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_customers_updated_at ON source_incremental.customers;
CREATE TRIGGER trg_customers_updated_at
BEFORE UPDATE ON source_incremental.customers
FOR EACH ROW EXECUTE FUNCTION source_incremental.set_updated_at();

DROP TRIGGER IF EXISTS trg_products_updated_at ON source_incremental.products;
CREATE TRIGGER trg_products_updated_at
BEFORE UPDATE ON source_incremental.products
FOR EACH ROW EXECUTE FUNCTION source_incremental.set_updated_at();

DROP TRIGGER IF EXISTS trg_orders_updated_at ON source_incremental.orders;
CREATE TRIGGER trg_orders_updated_at
BEFORE UPDATE ON source_incremental.orders
FOR EACH ROW EXECUTE FUNCTION source_incremental.set_updated_at();

DROP TRIGGER IF EXISTS trg_order_items_updated_at ON source_incremental.order_items;
CREATE TRIGGER trg_order_items_updated_at
BEFORE UPDATE ON source_incremental.order_items
FOR EACH ROW EXECUTE FUNCTION source_incremental.set_updated_at();

CREATE INDEX IF NOT EXISTS ix_customers_updated_at
    ON source_incremental.customers(updated_at);
CREATE INDEX IF NOT EXISTS ix_products_updated_at
    ON source_incremental.products(updated_at);
CREATE INDEX IF NOT EXISTS ix_orders_updated_at
    ON source_incremental.orders(updated_at);
CREATE INDEX IF NOT EXISTS ix_order_items_updated_at
    ON source_incremental.order_items(updated_at);

CREATE INDEX IF NOT EXISTS ix_orders_customer_id
    ON source_incremental.orders(customer_id);
CREATE INDEX IF NOT EXISTS ix_order_items_order_id
    ON source_incremental.order_items(order_id);
CREATE INDEX IF NOT EXISTS ix_order_items_product_id
    ON source_incremental.order_items(product_id);
